async function walkMarkdownFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...await walkMarkdownFiles(fullPath));
      continue;
    }

    if (entry.isFile() && entry.name.toLowerCase().endsWith('.md')) {
      files.push(fullPath);
    }
  }

  return files;
}

function parseFrontmatter(content) {
  if (!content.startsWith('---\n')) {
    return { frontmatter: null, body: content };
  }

  const endIndex = content.indexOf('\n---\n', 4);
  if (endIndex === -1) {
    return { frontmatter: null, body: content };
  }

  return {
    frontmatter: content.slice(4, endIndex),
    body: content.slice(endIndex + 5),
  };
}

function upsertFrontmatter(content, originalTitle, shortTitle) {
  const { frontmatter, body } = parseFrontmatter(content);
  const lines = frontmatter ? frontmatter.split('\n') : [];
  const outputLines = [];
  let hasTitle = false;
  let hasShortTitle = false;

  for (const line of lines) {
    if (/^title\s*:/u.test(line)) {
      outputLines.push(`title: "${originalTitle.replace(/"/g, '\\"')}"`);
      hasTitle = true;
      continue;
    }

    if (/^short_title\s*:/u.test(line)) {
      outputLines.push(`short_title: "${shortTitle.replace(/"/g, '\\"')}"`);
      hasShortTitle = true;
      continue;
    }

    outputLines.push(line);
  }

  if (!hasTitle) {
    outputLines.unshift(`title: "${originalTitle.replace(/"/g, '\\"')}"`);
  }

  if (!hasShortTitle) {
    outputLines.unshift(`short_title: "${shortTitle.replace(/"/g, '\\"')}"`);
  }

  return `---\n${outputLines.filter(Boolean).join('\n')}\n---\n${body.replace(/^\n?/, '\n')}`;
}

async function main() {
  const files = await walkMarkdownFiles(interviewsRoot);
  const targets = files.filter((filePath) => renameMap.has(path.basename(filePath, '.md')));

  if (dryRun) {
    for (const filePath of targets) {
      const originalTitle = path.basename(filePath, '.md');
      console.log(`${path.relative(projectRoot, filePath)} => ${renameMap.get(originalTitle)}.md`);
    }
    console.log(`Planned renames: ${targets.length}`);
    return;
  }

  for (const filePath of targets) {
    const originalTitle = path.basename(filePath, '.md');
    const shortTitle = renameMap.get(originalTitle);
    const nextPath = path.join(path.dirname(filePath), `${shortTitle}.md`);
    const content = await fs.readFile(filePath, 'utf8');
    const nextContent = upsertFrontmatter(content, originalTitle, shortTitle);

    await fs.writeFile(filePath, nextContent, 'utf8');

    if (filePath !== nextPath) {
      await fs.rename(filePath, nextPath);
    }
  }

  console.log(`Renamed ${targets.length} interview markdown files.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
